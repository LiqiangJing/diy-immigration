"""登录弹窗、密码、账户页、联系我们、条款页、演示页、手机版式。"""
import json, re, time
from common import *

with sync_playwright() as p:
    b = launch(p)
    ctx, page = new_page(b, "account")
    page.goto(BASE + "/")
    check("home: title", "DIY Immigration" in page.title())
    check("home: anonymous sidebar offers login", page.locator(".account-box button", has_text="登录 / 注册").count() == 1 and page.locator(".sync-state").count() == 0)

    # ---------- 登录弹窗 ----------
    page.locator(".account-box button", has_text="登录 / 注册").click()
    m = page.locator(".modal")
    check("auth: dialog has terms and privacy links", m.locator('a[href="/terms"]').count() == 1 and m.locator('a[href="/privacy"]').count() == 1)
    m.locator("input[type=email]").fill("not-an-email")
    m.get_by_role("button", name="发送验证码").click()
    check("auth: browser blocks an invalid email (no request sent)", m.locator(".dev-code").count() == 0 and m.locator("input[type=email]").evaluate("e => !e.validity.valid"))
    email = mail()
    m.locator("input[type=email]").fill(email)
    m.get_by_role("button", name="发送验证码").click()
    code = m.locator(".dev-code strong").inner_text()
    check("auth: code step shows the address", email in m.inner_text() and "10 分钟内有效" in m.inner_text())
    # 输错
    wrong = "000000" if code != "000000" else "111111"
    m.locator("input[inputmode=numeric]").fill(wrong)
    m.locator("button[type=submit]").click()
    m.locator(".notice").wait_for()
    check("auth: wrong code shows an error and stays open", "验证码不对" in m.locator(".notice").inner_text())
    m.locator("input[inputmode=numeric]").fill("12ab34")
    check("auth: code box only takes digits", m.locator("input[inputmode=numeric]").input_value() == "1234")
    # 换邮箱再回来：一分钟内重发会被拦
    m.get_by_role("button", name="换一个邮箱").click()
    m.get_by_role("button", name="发送验证码").click()
    m.locator(".notice").wait_for()
    check("auth: resending within a minute explains and goes straight back to the code box", "刚刚发过" in m.locator(".notice").inner_text() and m.locator("input[inputmode=numeric]").count() == 1, m.locator(".notice").inner_text())
    # 点遮罩关闭
    page.locator(".modal-scrim").click(position={"x": 5, "y": 5})
    check("auth: clicking outside closes the dialog", page.locator(".modal").count() == 0)
    # 用之前那个验证码登录（还有效）
    page.locator(".account-box button", has_text="登录 / 注册").click()
    m = page.locator(".modal")
    m.locator("input[type=email]").fill(email)
    db("update login_codes set sent_at=0 where email=?", (email,))
    m.get_by_role("button", name="发送验证码").click()
    code = m.locator(".dev-code strong").inner_text()
    m.locator("input[inputmode=numeric]").fill(code)
    m.locator("button[type=submit]").click()
    page.locator(".account-email", has_text=email).wait_for()
    check("auth: logged in, sidebar shows email and 200 credits", "200 credits" in page.locator(".account-credits").inner_text())
    page.locator(".sync-state.ok").wait_for(timeout=10000)
    check("auth: sync status shown", "已保存到云端" in page.locator(".sync-state").inner_text())

    # ---------- 账户页 ----------
    page.locator(".account-box button", has_text=email).click()
    check("account: balance card", page.locator(".balance strong").inner_text() == "200")
    packs = page.locator(".case-list .case-card")
    check("account: four top-up packs", packs.count() == 4, packs.count())
    check("account: top-up disabled with a notice when no payment method is configured (local)", packs.first.is_disabled() and page.locator(".notice", has_text="充值功能还没有开通").count() == 1)
    check("account: ledger shows the signup bonus", "注册赠送" in page.locator(".file-list").inner_text() and "+200" in page.locator(".file-list").inner_text())
    bal_text = page.locator(".balance small").inner_text()
    check("account: per-feature prices in the text match the server constants", "一键获取学术数据每次 20 个" in bal_text, bal_text)

    # ---------- 密码 ----------
    card = page.locator("section.card", has_text="登录密码")
    check("pw: says no password yet", "还没有设置密码" in card.inner_text())
    card.get_by_role("button", name="设置密码").click()
    card.locator("input[type=password]").nth(0).fill("abcdefgh1")
    card.locator("input[type=password]").nth(1).fill("abcdefgh2")
    card.get_by_role("button", name="保存密码").click()
    check("pw: mismatch is caught", "两次输入的密码不一样" in card.inner_text())
    card.locator("input[type=password]").nth(0).fill("short")
    card.locator("input[type=password]").nth(1).fill("short")
    card.get_by_role("button", name="保存密码").click()
    check("pw: too short is blocked by the form", card.locator("input[type=password]").first.evaluate("e => !e.validity.valid"))
    card.locator("input[type=password]").nth(0).fill("correct horse 9")
    card.locator("input[type=password]").nth(1).fill("correct horse 9")
    card.get_by_role("button", name="保存密码").click()
    card.locator(".notice", has_text="密码已保存").wait_for()
    check("pw: saved, card now offers to change it", card.get_by_role("button", name="修改密码").count() == 1 and "已设置密码" in card.inner_text())

    # ---------- 退出，再用密码登录 ----------
    page.get_by_role("button", name="退出登录").click()
    page.locator(".empty h3", has_text="还没有登录").wait_for()
    check("logout: account page shows the logged-out state", page.locator(".account-box button", has_text="登录 / 注册").count() == 1)
    page.locator(".empty").get_by_role("button", name="登录 / 注册").click()
    m = page.locator(".modal")
    m.get_by_role("button", name="用密码登录").click()
    m.locator("input[type=email]").fill(email)
    m.locator("input[type=password]").fill("wrong password")
    m.locator("button[type=submit]").click()
    m.locator(".notice").wait_for()
    check("pw login: wrong password message", "邮箱或密码不对" in m.locator(".notice").inner_text())
    m.locator("input[type=password]").fill("correct horse 9")
    m.locator("button[type=submit]").click()
    page.locator(".account-email", has_text=email).wait_for()
    check("pw login: success", page.locator("h2", has_text="账户").count() == 1)
    # 密码模式里可以切回验证码
    page.get_by_role("button", name="退出登录").click()
    page.locator(".empty").get_by_role("button", name="登录 / 注册").click()
    m = page.locator(".modal")
    m.get_by_role("button", name="用密码登录").click()
    m.get_by_role("button", name="用验证码登录").click()
    check("auth: can switch back to the code flow", m.get_by_role("button", name="发送验证码").count() == 1)
    m.get_by_role("button", name="取消").click()

    # ---------- 联系我们 ----------
    page.locator(".account-box button", has_text="联系我们").click()
    m = page.locator(".modal")
    check("contact: WeChat QR shown", m.locator(".wechat img").count() == 1 and m.locator(".wechat img").evaluate("e => e.naturalWidth > 0"))
    m.locator("input[type=email]").fill("visitor@example.com")
    m.locator("textarea").fill("hi")
    m.get_by_role("button", name="发送").click()
    m.locator(".notice").wait_for()
    check("contact: too-short message rejected", "具体一些" in m.locator(".notice").inner_text())
    mark = "TEST-" + uuid.uuid4().hex[:8]
    m.locator("textarea").fill(f"充值后 credit 没有到账，订单号 {mark}。")
    m.get_by_role("button", name="发送").click()
    m.get_by_text("收到了").wait_for()
    check("contact: confirmation names the reply address", "visitor@example.com" in m.inner_text())
    m.get_by_role("button", name="好的").click()
    check("contact: stored on the server", db("select count(*) from contact_messages where email='visitor@example.com' and message like ?", (f"%{mark}%",))[0][0] == 1)

    # ---------- 条款、隐私 ----------
    for path, title in [("/terms", "服务条款"), ("/privacy", "隐私政策")]:
        page.goto(BASE + path)
        check(f"legal: {path} renders", page.locator("h1").inner_text() == title and page.locator(".legal h2").count() >= 5, page.locator("h1").inner_text())
        check(f"legal: {path} has a way back", page.locator('.legal-nav a[href="/"]').count() == 1)
        text = page.locator(".legal").inner_text()
        check(f"legal: {path} has no leftover placeholders", not re.search(r"TODO|XXX|待定|待补充|\[.*?\]|lorem", text, re.I), re.findall(r"TODO|XXX|待定|待补充|\[.*?\]", text)[:5])
    shot(page, "privacy", full=True)

    # ---------- 演示页 ----------
    page.goto(BASE + "/demo")
    check("demo: no personal account shown (uses 'test')", "当前用户：test" in page.locator(".case-head").inner_text())
    page.get_by_role("button", name="按姓名查找").click()
    page.locator(".candidates button:not([disabled])").first.wait_for()
    page.locator(".candidates button:not([disabled])").first.click()
    page.locator(".demo-metrics").wait_for()
    btn = page.locator(".paper-pick .btn-accent").first
    btn.click()
    page.locator("details.notable").first.wait_for(timeout=10000)
    check("demo: analysis shows quoted citation contexts", page.locator("details.notable blockquote").count() > 0)
    chips = page.locator("details.notable .chips button")
    chips.nth(1).click()
    n_all = page.locator("details.notable").first.locator(".cite").count()
    chips.nth(0).click()
    n_pick = page.locator("details.notable").first.locator(".cite").count()
    check("demo: filter chips change the list", n_all >= n_pick > 0, (n_all, n_pick))
    page.get_by_role("button", name="生成引用地图").click()
    page.locator("svg.cite-map").wait_for(timeout=10000)
    check("demo: citation map draws countries", page.locator("svg.cite-map path").count() > 100)
    with page.expect_download() as dl:
        page.get_by_role("button", name="下载图片（PNG）").click()
    path = dl.value.path()
    from PIL import Image
    im = Image.open(path)
    check("demo: map downloads as a real PNG", dl.value.suggested_filename == "Citation Map.png" and im.size[0] > 1000, im.size)
    text = page.locator(".demo").inner_text()
    check("demo: prices quoted match the app (20 per fetch, 200 signup bonus)", "一次 20 credits" in text and "注册送 200 credits" in text)
    check("demo: 'start' leads to the app", page.locator('a.btn-accent[href="/"]').count() == 1)
    ctx.close()

    # ---------- 手机版式 ----------
    ctx, page = new_page(b, "mobile", mobile=True)
    email2 = mail()
    page.goto(BASE + "/")
    check("mobile: sidebar hidden, menu button visible", page.locator("button.menu-btn").is_visible() and not page.locator(".sidebar").evaluate("e => e.getBoundingClientRect().left >= 0 && e.getBoundingClientRect().right > 0 && getComputedStyle(e).visibility !== 'hidden' && e.getBoundingClientRect().left < 10 && e.classList.contains('open')"))
    check("mobile: no horizontal overflow on the chat page", page.evaluate("document.documentElement.scrollWidth <= window.innerWidth + 1"), page.evaluate("[document.documentElement.scrollWidth, window.innerWidth]"))
    page.locator("button.menu-btn").click()
    page.locator(".sidebar.open").wait_for()
    page.locator(".account-box button", has_text="登录 / 注册").click()
    m = page.locator(".modal")
    box = m.bounding_box()
    check("mobile: login dialog fits the screen", box["x"] >= 0 and box["x"] + box["width"] <= 390 + 1, box)
    m.locator("input[type=email]").fill(email2)
    m.get_by_role("button", name="发送验证码").click()
    m.locator("input[inputmode=numeric]").fill(m.locator(".dev-code strong").inner_text())
    m.locator("button[type=submit]").click()
    page.locator(".modal").wait_for(state="detached")
    if not page.locator(".sidebar.open").count():
        page.locator("button.menu-btn").click()
    page.locator(".nav button", has_text="我的档案").click()
    check("mobile: choosing a page closes the menu", page.locator(".sidebar.open").count() == 0)
    for i in range(4):
        page.locator(".profile-tabs button").nth(i).click()
        ok = page.evaluate("document.documentElement.scrollWidth <= window.innerWidth + 1")
        inner = page.locator(".cases.profile").evaluate("e => e.scrollWidth <= e.clientWidth + 1")
        check(f"mobile: profile tab {i + 1} has no horizontal overflow", ok and inner, page.locator(".cases.profile").evaluate("e => [e.scrollWidth, e.clientWidth]"))
    hs = [page.locator(".profile-tabs button").nth(i).bounding_box() for i in range(4)]
    check("mobile: profile tabs laid out two by two, each label on one line", hs[0]["y"] == hs[1]["y"] and hs[2]["y"] == hs[3]["y"] and hs[2]["y"] > hs[0]["y"] and all(h["height"] < 50 for h in hs), hs)
    shot(page, "mobile-profile-tabs")
    page.locator(".profile-tabs button").nth(3).click()
    page.locator("details.tips").nth(1).locator("summary").click()
    check("mobile: guidance example wraps instead of overflowing", page.locator("details.tips pre").first.evaluate("e => e.scrollWidth <= e.clientWidth + 1"))
    shot(page, "mobile-endeavor")
    # 案件和文档工作区
    page.locator("button.menu-btn").click(); page.locator(".nav button", has_text="案件").click()
    page.get_by_role("button", name="+ 创建第一个案件").click()
    page.get_by_role("button", name="创建", exact=True).click()
    page.locator(".guide li.step").first.wait_for()
    check("mobile: case guide has no horizontal overflow", page.locator(".cases").evaluate("e => e.scrollWidth <= e.clientWidth + 1"), page.locator(".cases").evaluate("e => [e.scrollWidth, e.clientWidth]"))
    tabs_ok = page.locator(".tabs").evaluate("e => e.scrollWidth <= e.clientWidth + 1 || getComputedStyle(e).overflowX !== 'visible'")
    check("mobile: case tabs fit or scroll", tabs_ok, page.locator(".tabs").evaluate("e => [e.scrollWidth, e.clientWidth, getComputedStyle(e).overflowX]"))
    shot(page, "mobile-guide")
    page.locator(".tabs button", has_text="文档").click()
    page.locator(".case-card", has=page.locator("strong", has_text="+ Petition Letter")).click()
    page.locator("textarea.doc-editor").wait_for()
    check("mobile: workspace shows document/chat switch", page.locator(".pane-tabs button").count() == 2 and page.locator(".pane-tabs").is_visible())
    page.locator(".pane-tabs button", has_text="聊天").click()
    check("mobile: chat pane visible after switching", page.locator(".chat-pane .composer textarea").is_visible() and not page.locator("textarea.doc-editor").is_visible())
    page.locator(".pane-tabs button", has_text="文档").click()
    check("mobile: document pane visible again", page.locator("textarea.doc-editor").is_visible())
    bar = page.locator(".doc-bar").evaluate("e => [e.scrollWidth, e.clientWidth]")
    check("mobile: document toolbar does not overflow", bar[0] <= bar[1] + 1, bar)
    shot(page, "mobile-doc")
    page.goto(BASE + "/demo")
    check("mobile: demo page has no horizontal overflow", page.locator(".cases").evaluate("e => e.scrollWidth <= e.clientWidth + 1"))
    b.close()
finish()
